export function totalHours(updates: PlatformUpdate[]) {
  return updates.reduce((sum, u) => sum + u.hours, 0);
}

export function groupByDate(updates: PlatformUpdate[]) {
  const map = new Map<string, PlatformUpdate[]>();
  for (const u of updates) {
    const list = map.get(u.date) ?? [];
    list.push(u);
    map.set(u.date, list);
  }
  return [...map.entries()].sort(([a], [b]) => (a < b ? 1 : -1));
}

function plural(n: number, one: string, few: string, many: string) {
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod10 === 1 && mod100 !== 11) return one;
  if ([2, 3, 4].includes(mod10) && ![12, 13, 14].includes(mod100)) return few;
  return many;
}

/** 5.2 → «5 часов 12 минут», 0.5 → «30 минут», 2 → «2 часа». */
export function formatHours(hours: number) {
  const totalMinutes = Math.round(hours * 60);
  const h = Math.floor(totalMinutes / 60);
  const m = totalMinutes % 60;
  const parts: string[] = [];
  if (h > 0) parts.push(`${h} ${plural(h, "час", "часа", "часов")}`);
  if (m > 0 || h === 0) parts.push(`${m} ${plural(m, "минута", "минуты", "минут")}`);
  return parts.join(" ");
}

export function formatDate(iso: string, { short = false } = {}) {
  const [y, m, d] = iso.split("-").map(Number);
  const date = new Date(y, m - 1, d);
  if (short) {
    return new Intl.DateTimeFormat("ru-RU", { day: "numeric", month: "long" }).format(date);
  }
  return new Intl.DateTimeFormat("ru-RU", { day: "numeric", month: "long", year: "numeric" }).format(date);
}
