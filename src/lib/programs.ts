const weekdayNames: Record<string, string> = {
  пн: "понедельник",
  вт: "вторник",
  ср: "среда",
  чт: "четверг",
  пт: "пятница",
  сб: "суббота",
  вс: "воскресенье",
};

export function weekdayFull(weekday: string) {
  return weekdayNames[weekday] ?? weekday;
}

export function getProgramById(id: string) {
  return programs.find((p) => p.id === id);
}

export function getRelatedPrograms(program: Program, count = 3) {
  const byDateAsc = (a: Program, b: Program) => a.dateISO.localeCompare(b.dateISO);
  const others = programs.filter((p) => p.id !== program.id);

  const sameCategory = others
    .filter((p) => p.categories.some((c) => program.categories.includes(c)))
    .sort(byDateAsc);
  const rest = others.filter((p) => !sameCategory.includes(p)).sort(byDateAsc);

  return [...sameCategory, ...rest].slice(0, count);
}
