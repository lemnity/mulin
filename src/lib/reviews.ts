/** Отзывы для страницы программы: сначала о её преподавателях, иначе — свежие отзывы о центре. */
export function getProgramReviews(lecturerIds: string[], limit = 3): { reviews: Review[]; aboutLecturer: boolean } {
  const byLecturer = reviews.filter((r) => r.lecturerIds?.some((id) => lecturerIds.includes(id)));
  if (byLecturer.length > 0) return { reviews: byLecturer.slice(0, limit), aboutLecturer: true };
  return { reviews: reviews.filter((r) => !r.lecturerIds).slice(0, limit), aboutLecturer: false };
}

export function formatReviewDate(iso: string) {
  const [y, m, d] = iso.split("-").map(Number);
  return new Intl.DateTimeFormat("ru-RU", { day: "numeric", month: "long", year: "numeric" }).format(new Date(y, m - 1, d));
}
